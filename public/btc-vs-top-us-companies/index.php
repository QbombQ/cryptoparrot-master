	function calculatePercentage(btc_mc){

		$('.bc_mc').html(format(btc_mc,2));

		$('[data-amount]').each(function(i,v){

			mc = $(this).data('amount');

			if(btc_mc < mc) percentage = (btc_mc * 100) / mc;
			else percentage = 100;

			progress = $(this).find('.progress-bar');

			progress.css('width',percentage.toFixed(2)+'%');
			progress.html(percentage.toFixed(0)+'%');  

		});
		 
	}

	function format(number,points) {
		number = parseFloat(number).toFixed(points); // decimal points
		number = abbreviateNumber(number);
		return number;
	}

	function pad (str, max) {
	  str = str.toString();
	  return str.length < max ? pad("0" + str, max) : str;
	}

	function abbreviateNumber(number) {

		


	    if (number >= 1000000000) {
	        return (number / 1000000000).toFixed(1).replace(/\.0$/, '') + ' Billion';
	    }
	     if (number >= 1000000) {
	        return (number / 1000000).toFixed(1).replace(/\.0$/, '') + 'M';
	     }
	     
	     if (number >= 1000) {
	        return (number / 1000).toFixed(1).replace(/\.0$/, '') + 'K';
	     }

	    if (number <= -1000000000) {
	        return (number / 1000000000).toFixed(1).replace(/\.0$/, '') + ' Billion';
	    }

	    if (number <= -1000000) {
	        return (number / 1000000).toFixed(1).replace(/\.0$/, '') + 'M';
	    }

	    if (number <= -1000) {
	        return (number / 1000).toFixed(1).replace(/\.0$/, '') + 'K';
	    }
	     
	     return number;
	}

