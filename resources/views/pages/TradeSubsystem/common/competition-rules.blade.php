<h6 class="font-weight-bold">How The Simulated Competition Winners Are Determined </h6>

<p class="font-weight-bold">The winners of the Top Trader Competition simulation are determined by measuring which participants have the largest overall increase in initial competition portfolio value percentage from the start and finish date/time of the simulated competition.</p>

<p class="lead font-weight-bold">Initial competition portfolio value</p>

<p>Initial competition portfolio value is $100k USD.</p>

<p>Final competition portfolio value is the USD sum of all the assets you hold in your competition portfolio and profit/loss of all open positions at the time of the simulated Top Trader Competition end.</p>

<p class="lead font-weight-bold">Competition portfolio value change calculationn</p>

<p>Competition Portfolio value change in % is calculated using the following formula: (FCPV * 100) / ICPV - 100 = Change</p>

<p>ICPV = Initial Competition Portfolio Value<br />
FCPV = Final Competition Portfolio Value</p> 

<p class="text-muted">E.g. (110000 * 100) / 100000 - 100 = +10%</p>

 
